    @classmethod
    def get_by_slug(cls, slug: str) -> Optional[ClubBannerProfile]:
        if not slug:
            return None
        s = slug.lower().strip().replace(" ", "-")
        s_clean = s[4:] if s.startswith("ucl-") else s

        if s in cls._PROFILES:
            return cls._PROFILES[s]
        if s_clean in cls._PROFILES:
            return cls._PROFILES[s_clean]

        for k, v in cls._PROFILES.items():
            if k == s_clean or k in s_clean or s_clean in k:
                return v

        # Dynamic fallback: query SQLite database so 100% of clubs have an authentic banner
        try:
            from .database import Database
            db = Database()
            club = db.get_club_by_id_or_slug(s) or db.get_club_by_id_or_slug(s_clean)
            if club:
                stadium = club.get("stadium_name") or club.get("stadium") or f"Estadio de {club.get('name')}"
                shield = club.get("shield_url") or f"https://a.espncdn.com/i/teamlogos/soccer/500/{club.get('espn_id', 'default')}.png"
                comp = club.get("competition") or "football"
                flag = "🇪🇸" if comp == "laliga" else ("🇮🇹" if comp == "serie_a" else "⭐")
                name = club.get("name") or s_clean.title()
                code = (club.get("shortname") or s_clean[:3]).upper()
                prof = ClubBannerProfile(
                    slug=slug,
                    name=name,
                    nickname=club.get("nickname") or name,
                    competition=comp,
                    badge_emoji="🛡️",
                    code=code,
                    primary_color=club.get("color") or "#004D98",
                    secondary_color=club.get("color_secondary") or "#FFFFFF",
                    shield_url=shield,
                    banner_url=shield,
                    stadium_name=stadium,
                    city=f"City of {name}",
                    country="Spain" if comp == "laliga" else ("Italy" if comp == "serie_a" else "Europe"),
                    country_flag=flag,
                    capacity=42000,
                    inaugurated=1965,
                    architectural_nickname=f"The Fortress of {name}",
                    team_motto=f"¡Orgullo y Pasión de {name}!",
                    anthem=f"Himno de {name}",
                    identity_summary=f"Storied {comp.replace('_', ' ').title()} club playing at {stadium}.",
                    atmosphere_rating=88,
                )
                cls._PROFILES[s] = prof
                cls._PROFILES[s_clean] = prof
                return prof
        except Exception:
            pass

        return None

    @classmethod
    def get_victory_banner(cls, slug_or_name: str, score_str: Optional[str] = None) -> Tuple[str, Optional[str]]:
        """
        Returns (victory_text_markup, banner_url) when a club is simulated or predicted to win.
        """
        prof = cls.get_by_slug(slug_or_name)
        score_tag = f" ({score_str})" if score_str else ""
        if not prof:
            clean_name = str(slug_or_name).replace("ucl-", "").replace("-", " ").title()
            lines = [
                f"🎉 🏆 <b>SIMULATION WINNER: {clean_name.upper()}{score_tag}!</b> 🏆 🎉",
                "🗣️ <i>\"Victory Through Determination & Tactical Excellence!\"</i>",
            ]
            return ("\n".join(lines), None)

        lines = [
            f"🎉 🏆 <b>SIMULATION WINNER: {prof.name.upper()}{score_tag}!</b> 🏆 🎉",
            f"🗣️ <i>\"{prof.team_motto}\"</i>",
            f"🏟️ <b>Venue:</b> {prof.stadium_name} · 👥 <b>Capacity:</b> <code>{prof.capacity:,}</code> seats",
            f"🔥 <b>Atmosphere Roar:</b> <code>{prof.atmosphere_rating}/100</code> · 🎵 <b>Anthem:</b> {prof.anthem}",
        ]
        return ("\n".join(lines), prof.banner_url)

    @classmethod
    def get_all(cls, competition: Optional[str] = None) -> List[ClubBannerProfile]:
        profs = list(cls._PROFILES.values())
        if competition:
            comp_norm = competition.lower().replace(" ", "_")
            return [p for p in profs if p.competition == comp_norm or comp_norm in p.competition]
        return profs
