    @classmethod
    def get_by_slug(cls, slug: str) -> Optional[ClubBannerProfile]:
        s = (slug or "").lower().replace(" ", "-").strip()
        if s.startswith("ucl-"):
            s = s[4:]
        if s in cls._PROFILES:
            return cls._PROFILES[s]
        for k, v in cls._PROFILES.items():
            if k in s or s in k:
                return v
        return None

    @classmethod
    def get_all(cls, competition: Optional[str] = None) -> List[ClubBannerProfile]:
        profs = list(cls._PROFILES.values())
        if competition:
            comp_norm = competition.lower().replace(" ", "_")
            return [p for p in profs if p.competition == comp_norm or comp_norm in p.competition]
        return profs
